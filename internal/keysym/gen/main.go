// Command gen writes the keysym name table from xkbcommon's
// xkbcommon-keysyms.h, so swm needs no libxkbcommon at run time.
//
// Usage: go run ./internal/keysym/gen -o table.go /path/to/xkbcommon-keysyms.h
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"strings"
)

// define matches one keysym definition, for example
// "#define XKB_KEY_Page_Up 0xff55 /* deprecated alias for Prior */".
var define = regexp.MustCompile(`^#define XKB_KEY_(\w+)\s+(0x[0-9a-fA-F]+)\s*(?:/\*(.*)\*/)?`)

func main() {
	out := flag.String("o", "", "output `file`")
	flag.Parse()
	if *out == "" || flag.NArg() != 1 {
		fmt.Fprintln(os.Stderr, "usage: gen -o table.go xkbcommon-keysyms.h")
		os.Exit(2)
	}
	if err := run(*out, flag.Arg(0)); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run(out, header string) error {
	f, err := os.Open(header)
	if err != nil {
		return err
	}
	defer f.Close()

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/keysym/gen from xkbcommon-keysyms.h. DO NOT EDIT.\n\n")
	b.WriteString("package keysym\n\n")
	b.WriteString("var table = [...]entry{\n")
	n := 0
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		m := define.FindStringSubmatch(sc.Text())
		if m == nil {
			continue
		}
		deprecated := strings.Contains(m[3], "deprecated") && !strings.Contains(m[3], "non-deprecated")
		fmt.Fprintf(&b, "\t{%q, %s, %t},\n", m[1], m[2], deprecated)
		n++
	}
	if err := sc.Err(); err != nil {
		return fmt.Errorf("read %s: %w", header, err)
	}
	if n == 0 {
		return fmt.Errorf("no keysyms found in %s", header)
	}
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		return fmt.Errorf("format: %w", err)
	}
	return os.WriteFile(out, src, 0o644)
}
